def render_csv(models: list[dict]) -> str:
    buf = io.StringIO()
    w = csv.DictWriter(buf, fieldnames=CSV_FIELDS, lineterminator="\n")
    w.writeheader()
    for m in models:
        row = {k: m.get(k) for k in CSV_FIELDS}
        row["model_type"] = "|".join(m["model_type"])
        row["free_endpoint"] = "true" if m["free_endpoint"] else "false"
        w.writerow({k: "" if v is None else v for k, v in row.items()})
    return buf.getvalue()


def outputs() -> dict:
    models, removed = load_json(MODELS), load_json(REMOVED)
    return {README: render_readme(models, removed), CSV: render_csv(models)}


def main(argv: list[str]) -> int:
    check = "--check" in argv
    stale = []
    for path, text in outputs().items():
        current = path.read_text(encoding="utf-8") if path.exists() else None
        if current != text:
            stale.append(path.name)
            if not check:
                write_text(path, text)
    if check and stale:
        print(f"Stale generated files: {', '.join(stale)}. Run: python scripts/generate_readme.py")
        return 1
    print("Generated files are up to date." if not stale else f"Wrote {', '.join(stale)}.")
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
