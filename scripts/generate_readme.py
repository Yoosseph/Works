#!/usr/bin/env python3
"""Generate README ranking tables from the canonical JSON dataset."""
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
DATA = ROOT / "data/models.json"
README = ROOT / "README.md"

def fmt(value):
    if value is None: return "N/A"
    for suffix, unit in (("T", 10**12), ("B", 10**9), ("M", 10**6), ("K", 10**3)):
        if value >= unit:
            n = value / unit
            return f"{n:.0f}{suffix}" if n.is_integer() else f"{n:.1f}{suffix}"
    return str(value)

def context(value):
    return "N/A" if value is None else fmt(value)

def rank_rows(models, free=False):
    rows = [m for m in models if (not free or m["free_endpoint"])]
    rows.sort(key=lambda m: (m["total_parameters"] is not None, m["total_parameters"] or -1), reverse=True)
    return rows

def md_rows(rows, full=False):
    out = []
    for i, m in enumerate(rows, 1):
        types = ", ".join(m["model_type"])
        if full:
            out.append(f'| {i} | {m["name"]} | {m["developer"]} | {fmt(m["total_parameters"])} | {fmt(m["active_parameters"])} | {m["architecture"]} | {context(m["context_length"])} | {types} | {m["endpoint_status"]} | [NVIDIA]({m["nvidia_url"]}) | [Source]({m["parameter_source"]}) |')
        else:
            out.append(f'| {i} | {m["name"]} | {m["developer"]} | {fmt(m["total_parameters"])} | {fmt(m["active_parameters"])} | {m["architecture"]} | {context(m["context_length"])} | {types} | [NVIDIA]({m["nvidia_url"]}) | [Source]({m["parameter_source"]}) |')
    return "\n".join(out)

def main():
    models = json.loads(DATA.read_text())
    free = rank_rows(models, True); all_models = rank_rows(models)
    largest = all_models[0]["name"] if all_models else "None"
    date = max((m["last_verified"] for m in models), default="Unknown")
    free_table = md_rows(free)
    full_table = md_rows(all_models, True)
    readme = f'''# NVIDIA API Model Rankings\n\nA maintained, source-backed ranking of models in NVIDIA's hosted API and NIM ecosystem, ordered by **total parameter count**.\n\n- **Models tracked:** {len(models)}\n- **Free hosted endpoint models:** {len(free)}\n- **Last verified:** {date}\n- **Largest tracked model:** {largest} ({fmt(all_models[0]["total_parameters"]) if all_models else "N/A"} total parameters)\n\n> The dataset is curated in [`data/models.json`](data/models.json). This README is generated by `scripts/generate_readme.py`; do not edit ranking tables by hand.\n\n## NVIDIA Free Hosted API Models\n\nThese models have a current NVIDIA model page that advertises hosted API access without a paid NVIDIA service being required at the time of verification. Availability, quotas, authentication, and regional restrictions can change; check the linked NVIDIA page before use.\n\n| # | Model | Developer | Total Parameters | Active Parameters | Architecture | Context Length | Model Type | NVIDIA Link | Source |\n|---:|---|---|---:|---:|---|---:|---|---|---|\n{free_table}\n\n## Full NVIDIA Model Catalog\n\nThis ranking includes all currently curated language and multimodal models, regardless of endpoint status. Models without a verified parameter count are retained at the bottom.\n\n| # | Model | Developer | Total Parameters | Active Parameters | Architecture | Context Length | Model Type | Endpoint Status | NVIDIA Link | Parameter Source |\n|---:|---|---|---:|---:|---|---:|---|---|---|---|\n{full_table}\n\nSee [CONTRIBUTING.md](CONTRIBUTING.md), [the methodology](docs/methodology.md), and [the source guide](docs/sources.md).\n\n## Caveats\n\nNVIDIA catalog availability, quotas, aliases, and free-tier policies change. A `Free Endpoint` label records the state observed on `last_verified`; it is not a guarantee of unlimited access.\n\n## License\n\nMIT. See [LICENSE](LICENSE).\n'''
    README.write_text(readme)

if __name__ == "__main__": main()
